#!/usr/bin/env node
// Builds public/_redirects for Cloudflare Pages from the hand-written source.
//
// 2026-10-05: Cloudflare Pages runs at most 100 dynamic rules (a rule with a
// `:placeholder` or `*`) and silently ignores the rest. The source file had
// grown to 577 `/:lang/...` rules, so everything after the 100th returned 404
// (measured live: rule 100 redirected, rule 101 did not). Static rules have a
// separate limit of 2,000, so each `/:lang/slug` rule is written out once per
// locale that the old URL actually existed in, in both slash forms — Pages
// matches static sources exactly, `/a` does not cover `/a/`.
//
// Edit data/redirects/pages-redirects.source.txt, then run
// `npm run redirects:build`. `--check` fails when public/_redirects is stale
// or a limit is exceeded.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const LOCALES = ["ko", "en", "ja", "zh", "fr", "es"];
const STATIC_LIMIT = 2_000;
const DYNAMIC_LIMIT = 100;
const root = process.cwd();
const sourcePath = path.join(root, "data/redirects/pages-redirects.source.txt");
const localesPath = path.join(root, "data/redirects/source-locales.json");
const outputPath = path.join(root, "public/_redirects");
const checkOnly = process.argv.includes("--check");

const sourceText = await readFile(sourcePath, "utf8");
// Old URLs that only ever existed in some locales. A slug missing from this
// map is expanded to all six, which is always safe but costs twelve rules.
const sourceLocales = JSON.parse(await readFile(localesPath, "utf8"));

const errors = [];
const staticRules = new Map();
const dynamicRules = [];

function addStatic(source, target, status, line) {
  const previous = staticRules.get(source);
  if (previous && previous.target !== target) {
    errors.push(`Conflicting targets for ${source} (line ${line}): ${previous.target} / ${target}`);
    return;
  }
  if (!previous) staticRules.set(source, { target, status });
}

sourceText.split(/\r?\n/).forEach((raw, index) => {
  const text = raw.trim();
  if (!text || text.startsWith("#")) return;
  const fields = text.split(/\s+/);
  if (fields.length !== 3 || !/^\d{3}$/.test(fields[2])) {
    errors.push(`Malformed rule at line ${index + 1}: ${raw}`);
    return;
  }
  const [source, target, status] = fields;
  const langOnly = source.startsWith("/:lang/") && !source.includes("*") && !/:(?!lang\b)[A-Za-z]/.test(source);
  if (langOnly && !target.includes(":splat")) {
    const slug = source.slice("/:lang/".length).replace(/\/$/, "");
    for (const locale of sourceLocales[slug] ?? LOCALES) {
      const localized = target.replaceAll(":lang", locale);
      addStatic(`/${locale}/${slug}`, localized, status, index + 1);
      addStatic(`/${locale}/${slug}/`, localized, status, index + 1);
    }
    return;
  }
  if (source.includes("*") || /\/:[A-Za-z]/.test(source)) {
    dynamicRules.push(`${source} ${target} ${status}`);
    return;
  }
  addStatic(source, target, status, index + 1);
});

if (staticRules.size > STATIC_LIMIT) {
  errors.push(`Static redirects ${staticRules.size} exceed the Pages limit ${STATIC_LIMIT}`);
}
if (dynamicRules.length > DYNAMIC_LIMIT) {
  errors.push(`Dynamic redirects ${dynamicRules.length} exceed the Pages limit ${DYNAMIC_LIMIT}`);
}

const output = [
  "# Generated by scripts/build-redirects.mjs — do not edit.",
  "# Source and the reasons for each rule: data/redirects/pages-redirects.source.txt",
  // Static rules MUST come first. Cloudflare's parser treats every rule after
  // the first dynamic one as dynamic too (to keep match order), so a static
  // rule placed below a wildcard counts against the 100 limit and is dropped.
  // Measured 2026-10-05: with the 33 wildcard rules on top, only the first 67
  // static rules worked.
  "# Static rules first, then dynamic rules in source order (first match wins).",
  ...[...staticRules].map(([source, rule]) => `${source} ${rule.target} ${rule.status}`),
  ...dynamicRules,
  "",
].join("\n");

if (checkOnly) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    errors.push("public/_redirects is missing; run npm run redirects:build");
  }
  if (current && current !== output) {
    errors.push("public/_redirects is stale; run npm run redirects:build");
  }
}

if (errors.length) {
  console.error(errors.map((error) => `ERROR: ${error}`).join("\n"));
  process.exit(1);
}
if (!checkOnly) await writeFile(outputPath, output);
console.log(
  `Pages redirects ${checkOnly ? "check" : "written"} | static=${staticRules.size}/${STATIC_LIMIT} | dynamic=${dynamicRules.length}/${DYNAMIC_LIMIT}`,
);
