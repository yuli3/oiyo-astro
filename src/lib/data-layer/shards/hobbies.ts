// Helper function to get hobbies by category
export function getHobbiesByCategory(category: string): Hobby[] {
  return HOBBIES.filter((hobby) => {
    if (Array.isArray(hobby.category)) {
      return hobby.category.includes(category);
    }
    return hobby.category === category;
  });
}

// Helper function to get hobby by ID
export function getHobbyById(id: string): Hobby | undefined {
  return HOBBIES.find((hobby) => hobby.id === id);
}
