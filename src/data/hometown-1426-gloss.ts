/** Fur bundles such as 豹狐狸山水獺皮 are listed as one item: describe them by the animals named. */
const ANIMALS: [string, { ko: string; en: string }][] = [
  ["虎", { ko: "호랑이", en: "tiger" }],
  ["豹", { ko: "표범", en: "leopard" }],
  ["熊", { ko: "곰", en: "bear" }],
  ["狐", { ko: "여우", en: "fox" }],
  ["狸", { ko: "삵", en: "wildcat" }],
  ["山水獺", { ko: "산달·수달", en: "otter" }],
  ["山獺", { ko: "산달", en: "otter" }],
  ["水獺", { ko: "수달", en: "otter" }],
  ["獐", { ko: "노루", en: "roe deer" }],
  ["鹿", { ko: "사슴", en: "deer" }],
];

export function gloss(item: string): { ko: string; en: string } | null {
  const hit = GLOSS[item];
  if (hit) return hit;
  const m = /^(.+?)(皮|毛)$/.exec(item);
  if (!m) return null;
  let rest = m[1].replace(/^[金各]色?/, "");
  const ko: string[] = [];
  const en: string[] = [];
  while (rest) {
    const a = ANIMALS.find(([k]) => rest.startsWith(k));
    if (!a) return { ko: "여러 짐승 가죽", en: "assorted furs" };
    if (!ko.includes(a[1].ko)) ko.push(a[1].ko);
    if (!en.includes(a[1].en)) en.push(a[1].en);
    rest = rest.slice(a[0].length);
  }
  if (!ko.length) return { ko: "여러 짐승 가죽", en: "assorted furs" };
  return m[2] === "毛" ? { ko: `${ko.join("·")} 털`, en: `${en.join(", ")} hair` } : { ko: `${ko.join("·")} 가죽`, en: `${en.join(", ")} furs` };
}
