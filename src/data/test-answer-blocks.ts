/**
 * 검사 페이지의 정적 "답변 블록" 데이터 — 한 줄 답 + 결과 유형 표 + 짧은 문답 3개.
 *
 * 왜 있나 (2026-11-04, UI·UX·SEO·AIEO 계획 3번): 검사 페이지는 첫 문항과 근거 표기만
 * 정적 HTML에 있고, "이 검사가 무엇을 보는지, 결과 유형이 무엇인지"는 클라이언트에서만
 * 보였다. 한국어 검사 126쪽 본문 중앙값 452자, 68%가 800자 미만. 검색("○○ 테스트 결과
 * 유형")과 AI 답변이 인용할 문장이 HTML에 없었다.
 *
 * 규칙
 * - 결과 유형 이름은 검사 컴포넌트가 실제로 보여 주는 이름과 같아야 한다(지어내지 않음).
 * - 결과를 단정하지 않는다. 진단 도구가 아닌 검사는 그 사실을 문답 하나로 밝힌다.
 * - 구조화 데이터는 이 블록의 보이는 글에서만 만든다: FAQPage 는 Layout 이 이 문답으로,
 *   Quiz 는 TestAnswerBlock.astro 가 문항 수·결과 유형으로 낸다. 그래서 자체 FAQPage·Quiz·
 *   TestExplainer 가 있는 페이지에는 넣지 않는다 — test-answer-blocks.test.ts 가 소스로 강제한다.
 * - 로케일이 없으면 그리지 않는다(영어로 대신 채우지 않음). 1차는 한국어.
 */
